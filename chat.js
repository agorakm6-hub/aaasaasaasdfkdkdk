bot.on('document', async (msg) => {
    const chatId = msg.chat.id;
    registerUser(msg);
    if (isBanned(chatId)) { await notifyBannedOnce(chatId); return; }
    if (!botEnabled && !isAdmin(chatId)) {
        await bot.sendMessage(chatId, '🛠 Бот временно не работает, вернитесь позже.');
        return;
    }

    const doc = msg.document;
    doc.file_name = sanitizeIncomingText(doc.file_name || '') || doc.file_name;
    if (doc.file_size && doc.file_size > MAX_FILE_BYTES) {
        await bot.sendMessage(chatId, `⚠️ Файл больше ${MAX_FILE_BYTES / 1024 / 1024} МБ, не могу проверить.`);
        return;
    }

    const isPdf = /\.pdf$/i.test(doc.file_name || '') || doc.mime_type === 'application/pdf';

    try {
        await bot.sendChatAction(chatId, 'typing');
        const link = await bot.getFileLink(doc.file_id);
        const res = await fetch(link);
        const buf = Buffer.from(await res.arrayBuffer());

        if (isPdf) {
            const pdfText = await extractPdfText(buf);
            if (!pdfText.trim()) {
                await bot.sendMessage(chatId, '📄 Не получилось извлечь текст из PDF — возможно, это скан-картинка без текстового слоя.');
                return;
            }
            const summary = await summarizePdf(doc.file_name || 'file.pdf', pdfText);
            await bot.sendMessage(chatId, `📄 Содержание файла «${doc.file_name || 'файл'}»:\n\n${summary}`);
            return;
        }

        // Грубая проверка, что это текстовый/кодовый файл, а не бинарник
        const sampleText = buf.toString('utf8', 0, Math.min(buf.length, 2000));
        const nonPrintableRatio = (sampleText.match(/[^\x09\x0A\x0D\x20-\x7Eа-яА-ЯёЁ]/g) || []).length / Math.max(sampleText.length, 1);
        if (nonPrintableRatio > 0.3) {
            await bot.sendMessage(chatId, '📄 Похоже, это бинарный файл (не код/текст/PDF) — такой анализ пока не поддерживается. Пришли скрипт, конфиг, package.json или PDF.');
            return;
        }

        const text = buf.toString('utf8');
        const wantsReview = isReviewRequest(sanitizeIncomingText(msg.caption || ''));
        if (wantsReview) {
            const review = await reviewCodeContent(doc.file_name || 'file', text);
            await bot.sendMessage(chatId, `🔍 Ревью кода «${doc.file_name || 'файл'}»:\n\n${review}`);
        } else {
            // Проверка файла на безопасность — не чаще одного раза в сутки на
            // человека, и запускается только по явному нажатию кнопки, а не
            // автоматически при загрузке файла.
            const userId = msg.from?.id || chatId;
            if (usedToday(verifyUsedDate, userId)) {
                await bot.sendMessage(chatId, '🛡 На сегодня проверка файла на безопасность уже использована (доступна 1 раз в день). Возвращайся завтра — лимит обновится автоматически.');
                return;
            }
            pendingVerification.set(String(userId), {
                chatId,
                fileName: doc.file_name || 'file',
                text,
                expires: Date.now() + PENDING_ACTION_TTL_MS,
            });
            await bot.sendMessage(
                chatId,
                `🛡 Готов проверить файл «${doc.file_name || 'файл'}» на безопасность.\n\nНа сегодня доступна 1 проверка файла — нажми кнопку ниже, чтобы запустить сканирование.`,
                { reply_markup: { inline_keyboard: [[{ text: '🔴 Проверить файл', callback_data: `vf:${userId}` }]] } }
            );
        }
    } catch (e) {
        console.error('file analysis error:', e);
        await bot.sendMessage(chatId, e.isQuotaError ? QUOTA_MESSAGE : `❌ Не получилось проверить файл: ${e.message}`);
    }
});

// ====== OCR ПО ФОТО (скриншот ошибки → правим текущий проект) ======
bot.on('photo', async (msg) => {
    const chatId = msg.chat.id;
    registerUser(msg);
    if (isBanned(chatId)) { await notifyBannedOnce(chatId); return; }
    if (!botEnabled && !isAdmin(chatId)) {
        await bot.sendMessage(chatId, '🛠 Бот временно не работает, вернитесь позже.');
        return;
    }
    const userId = msg.from?.id || chatId;

    try {
        await bot.sendChatAction(chatId, 'typing');
        const photo = msg.photo[msg.photo.length - 1]; // самое высокое разрешение из присланных размеров
        const link = await bot.getFileLink(photo.file_id);
        const res = await fetch(link);
        const buf = Buffer.from(await res.arrayBuffer());

        const worker = await createWorker('rus+eng');
        let ocrText = '';
        let confidence = null;
        try {
            const { data } = await worker.recognize(buf);
            ocrText = sanitizeIncomingText((data.text || '').trim());
            confidence = typeof data.confidence === 'number' ? data.confidence : null;
        } finally {
            await worker.terminate();
        }

        if (!looksLikeRealText(ocrText, confidence)) {
            await bot.sendMessage(chatId, '🖼 На картинке нет текста.');
            return;
        }

        // Проверяем безопасность распознанного текста ДО того, как он куда-либо
        // попадёт (в ответ пользователю или в промпт генерации кода) — иначе
        // картинка становится способом обойти текстовые ограничения бота.
        const isDangerous = await checkOcrTextSafety(ocrText);
        if (isDangerous) {
            const { justBanned, permanent } = recordHardViolation(userId);
            const banNote = justBanned ? '\n\n🚫 Это была 5-я попытка задать вопрос из категории жёстких нарушений — бан навсегда.' : '';
            await bot.sendMessage(chatId, `${HARD_REFUSAL_REPLY_TEXT}${banNote}`);
            return;
        }
        const safeOcrText = maskForbiddenWords(ocrText);

        if (lastCodeFiles.has(chatId)) {
            const requestText = `Вот текст ошибки, распознанный со скриншота:\n${safeOcrText}\n\nНайди причину этой ошибки в текущем коде проекта и пришли исправленный файл целиком.`;

            if (usedToday(genUsedDate, userId)) {
                await bot.sendMessage(chatId, '💻 На сегодня генерация/исправление кода уже использована (доступна 1 раз в день). Возвращайся завтра.');
                return;
            }
            pendingGeneration.set(String(userId), { chatId, requestText, expires: Date.now() + PENDING_ACTION_TTL_MS });
            await bot.sendMessage(
                chatId,
                `🖼 Распознал ошибку со скриншота, готов найти и исправить.\n\nНа сегодня доступна 1 генерация/правка кода — нажми кнопку, чтобы запустить.`,
                { reply_markup: { inline_keyboard: [[{ text: '🔴 Сгенерировать', callback_data: `gc:${userId}` }]] } }
            );
        } else {
            await bot.sendMessage(
                chatId,
                `🖼 Распознанный текст:\n\n${safeOcrText.slice(0, 1500)}\n\nЕсли это ошибка в коде — сначала попроси меня написать сам код (тогда я буду знать проект), и пришли этот же скрин ещё раз — тогда смогу его исправить.`
            );
        }
    } catch (e) {
        console.error('OCR error:', e);
        await bot.sendMessage(chatId, e.isQuotaError ? QUOTA_MESSAGE : `❌ Не получилось распознать изображение: ${e.message}`);
    }
});

// Список реально существующих команд бота — только они перехватываются
// отдельными bot.onText-хендлерами выше. Любое другое сообщение, даже если
// оно начинается с "/", не является командой и должно обрабатываться как
// обычный вопрос пользователя (иначе бот молча "проглатывает" сообщения
// вида "/почему небо голубое" вместо ответа на них).
const KNOWN_COMMANDS = ['/start', '/reset', '/settings', '/voice', '/voicemode', '/admin', '/unban'];
function isKnownCommand(text) {
    const firstWord = text.split(/\s/, 1)[0].toLowerCase();
    // отрезаем возможный "@ИмяБота" после команды (Telegram-группы часто
    // требуют такой формат, например "/reset@MelonAiBot")
    const bare = firstWord.split('@', 1)[0];
    return KNOWN_COMMANDS.includes(bare);
}

// ====== ОБЫЧНЫЕ СООБЩЕНИЯ ======
bot.on('message', async (msg) => {
    if (!msg.text) return;
    if (msg.text.startsWith('/') && isKnownCommand(msg.text)) return;

    // Чистим текст от null-байтов/управляющих символов/ANSI/zero-width
    // символов и обрезаем аномально длинные сообщения ДО того, как текст
    // попадёт хоть в одну проверку ниже (маскировка слов, детекция кода,
    // отправка в LLM и т.д.) — иначе через невидимые символы можно обойти
    // словарный фильтр, а через флуд повторов — положить TTS/OCR/regex.
    msg.text = sanitizeIncomingText(msg.text);
    if (!msg.text) return;

    const chatId = msg.chat.id;
    const userId = msg.from?.id || chatId; // ID для системы банов — не меняется при смене имени/юзернейма

    registerUser(msg);
    if (isBanned(chatId)) { await notifyBannedOnce(chatId); return; }

    if (!botEnabled && !isAdmin(chatId)) {
        await bot.sendMessage(chatId, '🛠 Бот временно не работает, вернитесь позже.');
        return;
    }

    // --- Админ отправляет текст рассылки всем ---
    if (isAdmin(chatId) && awaitingBroadcast.has(chatId)) {
        awaitingBroadcast.delete(chatId);
        const text = msg.text;
        let sent = 0, failed = 0;
        for (const u of users.values()) {
            if (u.banned) continue;
            try {
                await bot.sendMessage(Number(u.id), text);
                sent++;
            } catch (e) {
                failed++;
            }
        }
        await bot.sendMessage(chatId, `📢 Рассылка завершена. Доставлено: ${sent}, не доставлено: ${failed}.`);
        return;
    }

    // --- Админ отправляет текст одному конкретному пользователю ---
    if (isAdmin(chatId) && awaitingDirectMessage.has(chatId)) {
        const targetId = awaitingDirectMessage.get(chatId);
        awaitingDirectMessage.delete(chatId);
        try {
            await bot.sendMessage(Number(targetId), msg.text);
            await bot.sendMessage(chatId, `✅ Сообщение отправлено пользователю ${targetId}.`);
        } catch (e) {
            await bot.sendMessage(chatId, `❌ Не получилось отправить: ${e.message}`);
        }
        return;
    }

    // --- Любой пользователь пишет сообщение создателю через /settings ---
    if (awaitingAdminContactMessage.has(chatId)) {
        awaitingAdminContactMessage.delete(chatId);
        const senderName = msg.from?.first_name || 'Пользователь';
        const username = msg.from?.username ? ` (@${msg.from.username})` : '';
        for (const adminId of ADMIN_IDS) {
            try {
                await bot.sendMessage(Number(adminId), `✉️ Сообщение от ${senderName}${username} [ID ${chatId}]:\n\n${msg.text}`);
            } catch (e) {
                console.error('contact admin send error:', e.message);
            }
        }
        await bot.sendMessage(chatId, '✅ Ваше сообщение отправлено.');
        return;
    }

    // --- Единая проверка безопасности для ЛЮБОГО текстового сообщения ---
    // Раньше запросы на ревью/генерацию кода и озвучку обрабатывались раньше
    // этой проверки и полностью её обходили. Теперь каждое сообщение сначала
    // анализируется как обычный вопрос пользователя (а не как отдельная
    // "команда" со своими правилами), и только потом маршрутизируется в
    // конкретную функцию — так эскалация банов работает одинаково для всех
    // путей, а не только для обычного чата.
    if (maskForbiddenWords(msg.text) !== msg.text) {
        const { justBanned, durationMs } = recordIllegalQuestion(userId);
        if (justBanned) {
            await bot.sendMessage(chatId, `🚫 Обнаружен незаконный вопрос. Это была ${escalationCountLabel(userId, 'illegal')}-я подобная попытка — бан на ${formatDuration(durationMs)}.`, msg.chat.type !== 'private' ? { reply_to_message_id: msg.message_id } : {});
            return;
        }
    }

    // --- Ревью кода (качество/баги, отдельно от анализа безопасности) ---
    if (isReviewRequest(msg.text)) {
        const fenceMatch = msg.text.match(/```[a-zA-Z0-9]*\n([\s\S]*?)```/);
        let codeToReview = null;
        let labelName = 'вставленный код';
        if (fenceMatch) {
            codeToReview = fenceMatch[1];
        } else if (lastCodeFiles.has(chatId)) {
            const files = lastCodeFiles.get(chatId);
            codeToReview = files.map((f) => `// ФАЙЛ: ${f.filename}\n${f.content}`).join('\n\n');
            labelName = 'последний сгенерированный проект';
        }

        if (!codeToReview) {
            await bot.sendMessage(chatId, 'Пришли код файлом, или вставь его в тройных кавычках (```код```), либо сначала попроси меня что-то написать — тогда смогу сделать ревью того проекта.');
            return;
        }

        await bot.sendChatAction(chatId, 'typing');
        try {
            const review = await reviewCodeContent(labelName, codeToReview);
            await bot.sendMessage(chatId, `🔍 Ревью кода:\n\n${review}`);
        } catch (e) {
            await bot.sendMessage(chatId, e.isQuotaError ? QUOTA_MESSAGE : `❌ Ошибка ревью: ${e.message}`);
        }
        return;
    }

    // --- Запрос на генерацию кода (в том числе доработку уже присланного и
    //     автоматическую починку по вставленному тексту ошибки) ---
    if (isCodeRequest(msg.text, chatId)) {
        const isErrorText = looksLikeErrorText(msg.text);
        const requestText = isErrorText
            ? `Вот текст ошибки:\n${msg.text.trim()}\n\nНайди причину этой ошибки в текущем коде проекта и пришли исправленный файл целиком.`
            : msg.text.trim();

        if (usedToday(genUsedDate, userId)) {
            await bot.sendMessage(chatId, '💻 На сегодня генерация кода уже использована (доступна 1 раз в день). Возвращайся завтра — лимит обновится автоматически.', isGroup ? { reply_to_message_id: msg.message_id } : {});
            return;
        }
        pendingGeneration.set(String(userId), { chatId, requestText, expires: Date.now() + PENDING_ACTION_TTL_MS });
        await bot.sendMessage(
            chatId,
            `💻 Готов сгенерировать код по твоему запросу.\n\nНа сегодня доступна 1 генерация — нажми кнопку, чтобы запустить.`,
            { reply_markup: { inline_keyboard: [[{ text: '🔴 Сгенерировать', callback_data: `gc:${userId}` }]] }, ...(isGroup ? { reply_to_message_id: msg.message_id } : {}) }
        );
        return;
    }

    // --- Запрос на озвучку текста голосовым сообщением ---
    if (isVoiceRequest(msg.text)) {
        const textToSpeak = extractVoiceText(msg);
        if (!textToSpeak) {
            await bot.sendMessage(chatId, 'Напиши текст для озвучки после слова "озвучь", или ответь этим словом на сообщение с текстом.');
            return;
        }
        try {
            await bot.sendChatAction(chatId, 'record_voice');
            await sendAsVoice(chatId, textToSpeak);
        } catch (e) {
            console.error('voice error:', e);
            await bot.sendMessage(chatId, '❌ Не получилось сделать голосовое сообщение, попробуй позже.');
        }
        return;
    }

    const isGroup = msg.chat.type === 'group' || msg.chat.type === 'supergroup';
    let question = msg.text.trim();

    if (isGroup) {
        const isReplyToBot = !!(msg.reply_to_message && msg.reply_to_message.from && BOT_ID && msg.reply_to_message.from.id === BOT_ID);
        if (!isReplyToBot) {
            const lower = question.toLowerCase();
            if (!lower.startsWith(TRIGGER_WORD)) return;
            question = question.slice(TRIGGER_WORD.length).replace(/^[,:\s-]+/, '').trim();
            if (!question) {
                await bot.sendMessage(chatId, `👋 Слушаю! Напиши, например: "${TRIGGER_WORD} как сварить борщ?"`, { reply_to_message_id: msg.message_id });
                return;
            }
        }
    }

    if (!isAdmin(chatId) && getDailyQuestionCount(userId) >= DAILY_QUESTION_LIMIT) {
        await bot.sendMessage(chatId, `⏳ Лимит ${DAILY_QUESTION_LIMIT} вопросов в день исчерпан. Возвращайся завтра!`);
        return;
    }
    incrementDailyQuestionCount(userId);

    await bot.sendChatAction(chatId, 'typing');
    const typingInterval = setInterval(() => bot.sendChatAction(chatId, 'typing').catch(() => {}), 4000);

    const userName = msg.from?.first_name || 'Пользователь';
    const systemPrompt = SYSTEM_PROMPT;
    try {
        // Проверка на запрещённые слова уже была сделана один раз для этого
        // сообщения в общем блоке безопасности выше (до маршрутизации по
        // типу запроса) — здесь просто маскируем текст перед отправкой в LLM,
        // повторно не считая попытку и не баня второй раз за одно сообщение.
        const maskedQuestion = maskForbiddenWords(question);

        const rawReply = await askFreeLLM(chatId, maskedQuestion, userName, systemPrompt);
        const moderated = resolveModerated(rawReply, userId);
        let reply;
        let isViolation = !!moderated.violation;

        if (isViolation) {
            reply = moderated.text;
        } else {
            // Второй, независимый рубеж защиты — см. комментарий у
            // isReplyUnsafe(). Ловит случаи, когда модель ответила опасно,
            // но сама не распознала это как нарушение своих же правил.
            const unsafe = await isReplyUnsafe(rawReply);
            if (unsafe) {
                const { justBanned } = recordHardViolation(userId);
                const banNote = justBanned ? '\n\n🚫 Это была 5-я попытка задать вопрос из категории жёстких нарушений — бан навсегда.' : '';
                reply = `${HARD_REFUSAL_REPLY_TEXT}${banNote}`;
                isViolation = true;
            } else {
                reply = maskForbiddenWords(rawReply);
            }
        }

        pushHistory(chatId, userName, maskedQuestion);
        pushHistory(chatId, 'Бот', reply);
        await bot.sendMessage(chatId, reply, isGroup ? { reply_to_message_id: msg.message_id } : {});

        if (voiceMode.has(chatId) && !isViolation) {
            try {
                await bot.sendChatAction(chatId, 'record_voice');
                await sendAsVoice(chatId, reply);
            } catch (voiceErr) {
                console.error('voice reply error:', voiceErr.message);
                await bot.sendMessage(chatId, `🔇 Не получилось сделать голосовое (${voiceErr.message}). Текстовый ответ выше.`);
            }
        }
    } catch (e) {
        console.error('askFreeLLM error:', e.message);
        const errText = e.isQuotaError ? QUOTA_MESSAGE : `❌ Ошибка: ${e.message}`;
        await bot.sendMessage(chatId, errText, isGroup ? { reply_to_message_id: msg.message_id } : {});
    } finally {
        clearInterval(typingInterval);
    }
});
