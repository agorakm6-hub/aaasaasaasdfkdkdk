// ====== НЕЗАВИСИМАЯ ПРОВЕРКА ГОТОВОГО ОТВЕТА (второй рубеж защиты) ======
// Основная защита в SYSTEM_PROMPT работает только если сама модель понимает,
// что её пытаются обмануть — а при удачном обходе правил модель может не
// заметить это и просто ответить как обычно, без служебного токена. Чтобы
// не полагаться только на "самосознание" модели, каждый обычный ответ в
// чате дополнительно проверяется вторым, отдельным и более простым
// запросом — специально БЕЗ истории диалога и системного промпта бота,
// чтобы более ранний обход правил в разговоре никак не влиял на эту
// проверку. Это не даёт стопроцентной гарантии (идеальной защиты для
// языковых моделей не существует в принципе), но перекрывает основную
// часть случаев, когда первый рубеж не сработал.
const REPLY_SAFETY_CHECK_PROMPT = `Тебе показывают текст — уже готовый ответ ассистента пользователю чат-бота. Ты не сам ассистент и не продолжаешь разговор, а проверяешь чужой текст со стороны.

Проверь только одно: даёт ли этот текст реальную практическую пользу для причинения вреда, а именно — содержит ли он:
- конкретные шаги, пропорции, компоненты или технические детали изготовления оружия, взрывчатки или отравляющих веществ;
- конкретные шаги синтеза наркотиков или дозировки/способы причинения вреда себе или другим;
- сексуализированное описание персонажа, который по контексту является ребёнком;
- реально рабочий вредоносный код (вирус, шифровальщик, эксплойт, инструмент для взлома чужих аккаунтов, фишинг-страницу).

Простое упоминание этих тем, отказ помочь, нейтральное определение, обсуждение новости или истории — это НЕ нарушение. Ответь строго одним словом без пояснений и знаков препинания: ОПАСНО — если найден хотя бы один из перечисленных случаев, или НОРМА — если ничего из этого нет.`;

async function isReplyUnsafe(replyText) {
    if (!replyText || replyText.length < 3) return false;
    try {
        const verdict = await askFreeLLMOnce(REPLY_SAFETY_CHECK_PROMPT, replyText.slice(0, 4000));
        return /ОПАСНО/i.test((verdict || '').trim());
    } catch (e) {
        // Если контрольный запрос не удался (например, кончилась квота) — не
        // блокируем ответ из-за технической ошибки, чтобы бот не переставал
        // отвечать полностью. Первый рубеж защиты (SYSTEM_PROMPT + токены)
        // продолжает работать независимо от этой функции.
        console.error('reply safety check error:', e.message);
        return false;
    }
}


// Модель вместо расплывчатых формулировок отвечает строго одним токеном,
// когда обнаруживает джейлбрейк или жёсткое нарушение — так это можно
// программно и надёжно поймать (в отличие от сопоставления с изменчивой
// человеческой фразой) и завязать на систему банов.
const JAILBREAK_TOKEN = '<<JB_DETECTED>>';
const HARD_REFUSAL_TOKEN = '<<HARD_REFUSAL>>';
const JAILBREAK_REPLY_TEXT = 'Так не получится 🙂 Я не могу отключить свои правила безопасности, даже если попросить об этом необычным способом или другими словами. Задай, пожалуйста, обычный вопрос — с радостью помогу.';
