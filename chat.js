async function handleGenerateCodeCallback(query, chatId, data) {
    const ownerId = data.slice('gc:'.length);
    const requesterId = String(query.from?.id || '');

    if (requesterId !== ownerId) {
        await bot.answerCallbackQuery(query.id, { text: 'Это не твой запрос на генерацию' });
        return;
    }

    const pending = pendingGeneration.get(ownerId);
    if (!pending || Date.now() > pending.expires) {
        pendingGeneration.delete(ownerId);
        await bot.answerCallbackQuery(query.id, { text: 'Время подтверждения истекло, повтори запрос' });
        return;
    }

    if (usedToday(genUsedDate, ownerId)) {
        pendingGeneration.delete(ownerId);
        await bot.answerCallbackQuery(query.id, { text: 'На сегодня лимит уже использован' });
        return;
    }

    pendingGeneration.delete(ownerId);
    markUsedToday(genUsedDate, ownerId);
    await bot.answerCallbackQuery(query.id, { text: 'Генерирую код...' });
    await bot.editMessageReplyMarkup({ inline_keyboard: [] }, { chat_id: pending.chatId, message_id: query.message.message_id }).catch(() => {});
    await bot.sendChatAction(pending.chatId, 'upload_document');

    try {
        const result = await generateCodeFiles(pending.requestText, lastCodeFiles.get(pending.chatId));
        if (result.refused) {
            const { justBanned } = recordHardViolation(ownerId);
            const banNote = justBanned ? '\n\n🚫 Это была 5-я попытка задать вопрос из категории жёстких нарушений — бан навсегда.' : '';
            await bot.sendMessage(pending.chatId, `${HARD_REFUSAL_REPLY_TEXT}${banNote}`);
        } else if (result.tooBig) {
            await bot.sendMessage(pending.chatId, `⚠️ Получившийся код весит около ${result.sizeKb} КБ — это больше лимита в 150 КБ. Опиши задачу проще/уже и попробуй завтра — на сегодня генерация уже использована.`);
        } else if (result.files && result.files.length) {
            lastCodeFiles.set(pending.chatId, result.files);
            for (const f of result.files) {
                const safeName = f.filename.replace(/[^a-zA-Z0-9._-]/g, '_');
                const tmpPath = path.join(os.tmpdir(), `${Date.now()}_${randInt(1000, 9999)}_${safeName}`);
                fs.writeFileSync(tmpPath, f.content, 'utf8');
                await bot.sendDocument(pending.chatId, tmpPath, {}, { filename: f.filename });
                fs.unlink(tmpPath, () => {});
            }
            await bot.sendMessage(
                pending.chatId,
                result.warning
                    ? '⚠️ Код сгенерирован, но при автоматической проверке остались замечания по синтаксису — обязательно проверь перед использованием.'
                    : '✅ Готово — файл(ы) целиком. На сегодня генерация уже использована, новую можно будет запросить завтра.'
            );
        } else {
            await bot.sendMessage(pending.chatId, '❌ Не получилось сгенерировать код, попробуй завтра переформулировать запрос.');
        }
    } catch (e) {
        console.error('code gen error:', e);
        await bot.sendMessage(pending.chatId, e.isQuotaError ? QUOTA_MESSAGE : `❌ Ошибка генерации кода: ${e.message}`);
    }
}

