// ====== САНИТАЙЗЕР ВХОДЯЩЕГО ТЕКСТА (защита от "мусорных"/атакующих payload'ов) ======
// Ловит типичные фаззинг-пейлоады: нуль-байты и потоки управляющих символов,
// ANSI escape-коды (могут испортить вывод в терминале сервера), огромные
// повторы одного символа/эмодзи (DoS для TTS/OCR/regex), и, что важнее всего,
// zero-width символы — их подсовывают ВНУТРЬ слов (например "уби<ZWSP>йство"),
// чтобы разорвать совпадение с FORBIDDEN_WORDS и обойти маскировку/бан.
const MAX_INPUT_LENGTH = 4000; // с запасом покрывает лимит Telegram на текстовое сообщение (4096)
const ZERO_WIDTH_RE = /[\u200B\u200C\u200D\uFEFF\u2060]/g;
const ANSI_ESCAPE_RE = /\x1b\[[0-9;]*[a-zA-Z]/g;
// eslint-disable-next-line no-control-regex
const CONTROL_CHARS_RE = /[\x00-\x08\x0B\x0C\x0E-\x1F\x7F]/g; // всё, кроме \t(\x09) \n(\x0A) \r(\x0D)
const LONG_RUN_RE = /(.)\1{199,}/gsu; // один и тот же символ подряд 200+ раз

function sanitizeIncomingText(text) {
    if (!text) return text;
    let result = text
        .replace(ANSI_ESCAPE_RE, '')
        .replace(ZERO_WIDTH_RE, '')
        .replace(CONTROL_CHARS_RE, '')
        .replace(LONG_RUN_RE, (m, ch) => ch.repeat(50) + ' …(повтор символа обрезан)… '); // не убиваем совсем, чтобы легитимный "длинный забор из ---" не ломался, просто режем флуд
    if (result.length > MAX_INPUT_LENGTH) {
        result = result.slice(0, MAX_INPUT_LENGTH) + '\n…(сообщение обрезано, слишком длинное)';
    }
    return result;
}

