// ====== ПРОВЕРКА КАЧЕСТВА И БЕЗОПАСНОСТИ РАСПОЗНАННОГО С ФОТО ТЕКСТА ======
// Tesseract на фото БЕЗ текста часто всё равно возвращает мусорную "строку"
// (случайные символы, принятые за буквы) вместо пустой строки — простой
// проверки на !ocrText недостаточно. Отсеиваем по confidence и по доле
// настоящих букв/цифр в результате.
function looksLikeRealText(text, confidence) {
    if (!text) return false;
    const cleaned = text.replace(/\s+/g, '');
    if (cleaned.length < 3) return false;
    if (confidence != null && confidence < 45) return false;
    const alnumRatio = (cleaned.match(/[a-zA-Zа-яА-ЯёЁ0-9]/g) || []).length / cleaned.length;
    if (alnumRatio < 0.55) return false;
    if (!/[a-zA-Zа-яА-ЯёЁ]{3,}/.test(text)) return false; // хотя бы одно похожее на слово сочетание букв
    return true;
}

