// Отдельно от verifyUsedDate/genUsedDate (те — "1 раз в день" на конкретную
// функцию), этот лимит — общий счётчик для обычного чата. Ключ — userId, не
// chatId, чтобы нельзя было обойти лимит, написав из другого чата с тем же
// аккаунтом (например, из группы вместо личных сообщений).
const DAILY_QUESTION_LIMIT = 50;
const questionCountToday = new Map(); // userId -> { date: 'YYYY-MM-DD', count: N }
function getDailyQuestionCount(userId) {
    const entry = questionCountToday.get(String(userId));
    if (!entry || entry.date !== todayStr()) return 0;
    return entry.count;
}
function incrementDailyQuestionCount(userId) {
    const key = String(userId);
    const today = todayStr();
    const entry = questionCountToday.get(key);
    if (!entry || entry.date !== today) {
        questionCountToday.set(key, { date: today, count: 1 });
        return 1;
    }
    entry.count++;
    return entry.count;
}

