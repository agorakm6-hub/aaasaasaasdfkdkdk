function toSafeRegex(word) {
    return /^[a-zа-яё]/i.test(word) && /[а-яё]/i.test(word[0])
        ? new RegExp(`(?<![а-яё])${word}`, 'i')
        : new RegExp(`\\b${word}`, 'i');
}

