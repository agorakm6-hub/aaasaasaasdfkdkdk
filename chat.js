// Ключ — числовой Telegram ID пользователя (msg.from.id), а не имя/юзернейм/
// чат: он не меняется, даже если человек сменил имя, юзернейм или удалил и
// заново открыл чат с ботом — бан всё равно останется в силе.
//
// Расписание для джейлбрейков и незаконных вопросов (независимо друг от
// друга, у каждого свой счётчик): 10 попыток → бан 1 час, +3 (13) → 5 часов,
// +2 (15) → 12 часов, +1 (16) → 1 день, и далее КАЖДАЯ следующая попытка —
// снова +1 день.
// Жёсткие нарушения (оружие/взрывчатка/наркосинтез для вреда, CSAM) — своя
// отдельная шкала: 5 попыток → бан навсегда.
const violations = new Map(); // userId(string) -> { jbAttempts, jbStage, illegalAttempts, illegalStage, hardAttempts, bannedUntil, banReason }

function getViolationState(userId) {
    const key = String(userId);
    if (!violations.has(key)) {
        violations.set(key, { jbAttempts: 0, jbStage: 0, illegalAttempts: 0, illegalStage: 0, hardAttempts: 0, bannedUntil: 0, banReason: '' });
    }
    return violations.get(key);
}

const ESCALATION_THRESHOLDS = [10, 13, 15, 16]; // накопленное число попыток, при котором срабатывает очередная стадия
const ESCALATION_DURATIONS_MS = [
    1 * 3600 * 1000,   // 1 час
    5 * 3600 * 1000,   // 5 часов
    12 * 3600 * 1000,  // 12 часов
    24 * 3600 * 1000,  // 1 день (и дальше — каждая следующая попытка снова на 1 день)
];
function escalationThreshold(stage) {
    if (stage < ESCALATION_THRESHOLDS.length) return ESCALATION_THRESHOLDS[stage];
    return ESCALATION_THRESHOLDS[ESCALATION_THRESHOLDS.length - 1] + (stage - ESCALATION_THRESHOLDS.length + 1);
}
function escalationDuration(stage) {
    return ESCALATION_DURATIONS_MS[Math.min(stage, ESCALATION_DURATIONS_MS.length - 1)];
}

function applyBan(v, durationMs, reason) {
    v.bannedUntil = Date.now() + durationMs;
    v.banReason = reason;
}

// Возвращает объект с фактом попытки — используется, чтобы сразу сообщить
// пользователю "тебя забанили на X" в момент срабатывания.
function recordJailbreakAttempt(userId) {
    const v = getViolationState(userId);
    v.jbAttempts++;
    if (v.jbAttempts >= escalationThreshold(v.jbStage)) {
        const durationMs = escalationDuration(v.jbStage);
        v.jbStage++;
        applyBan(v, durationMs, 'jailbreak');
        return { justBanned: true, durationMs };
    }
    return { justBanned: false };
}

function recordIllegalQuestion(userId) {
    const v = getViolationState(userId);
    v.illegalAttempts++;
    if (v.illegalAttempts >= escalationThreshold(v.illegalStage)) {
        const durationMs = escalationDuration(v.illegalStage);
        v.illegalStage++;
        applyBan(v, durationMs, 'illegal');
        return { justBanned: true, durationMs };
    }
    return { justBanned: false };
}

function recordHardViolation(userId) {
    const v = getViolationState(userId);
    v.hardAttempts++;
    if (v.hardAttempts >= 5) {
        v.bannedUntil = Infinity;
        v.banReason = 'hard';
        return { justBanned: true, permanent: true };
    }
    return { justBanned: false };
}

function isViolationBanned(userId) {
    const v = violations.get(String(userId));
    if (!v || !v.bannedUntil) return false;
    if (v.bannedUntil === Infinity) return true;
    return Date.now() < v.bannedUntil;
}

function formatDuration(ms) {
    if (ms >= 24 * 3600 * 1000) return `${Math.round(ms / (24 * 3600 * 1000))} дн.`;
    if (ms >= 3600 * 1000) return `${Math.round(ms / 3600000)} ч.`;
    return `${Math.round(ms / 60000)} мин.`;
}

function banReasonLabel(reason) {
    if (reason === 'jailbreak') return 'повторные попытки взлома системного промпта';
    if (reason === 'illegal') return 'повторные незаконные вопросы';
    if (reason === 'hard') return 'запросы на изготовление оружия/взрывчатки/наркотиков или контент с несовершеннолетними';
    return 'нарушение правил';
}

function getViolationBanMessage(userId) {
    const v = violations.get(String(userId));
    if (!v || !v.bannedUntil) return null;
    if (v.bannedUntil === Infinity) {
        return `🚫 Ты забанен навсегда (причина: ${banReasonLabel(v.banReason)}). Это решение не подлежит пересмотру ботом.`;
    }
    const remaining = v.bannedUntil - Date.now();
    if (remaining <= 0) return null;
    return `🚫 Ты временно забанен на ${formatDuration(remaining)} (причина: ${banReasonLabel(v.banReason)}). Попробуй снова позже.`;
}

