// Разбирает ответ модели на предмет служебных токенов. userId нужен, чтобы
// сразу применить бан по эскалации и вернуть готовый текст для пользователя
// (либо обычный отказ, либо сообщение о бане, если сработал очередной порог).
function resolveModerated(rawReply, userId) {
    const trimmed = (rawReply || '').trim();

    if (trimmed.includes(JAILBREAK_TOKEN)) {
        const { justBanned, durationMs } = recordJailbreakAttempt(userId);
        if (justBanned) {
            return { text: `${JAILBREAK_REPLY_TEXT}\n\n🚫 Это была ${escalationCountLabel(userId, 'jb')}-я подозрительная попытка — бан на ${formatDuration(durationMs)}.`, violation: 'jailbreak' };
        }
        return { text: JAILBREAK_REPLY_TEXT, violation: 'jailbreak' };
    }

    if (trimmed.includes(HARD_REFUSAL_TOKEN)) {
        const { justBanned, permanent } = recordHardViolation(userId);
        if (justBanned) {
            return { text: `${HARD_REFUSAL_REPLY_TEXT}\n\n🚫 Это была 5-я попытка задать вопрос из категории жёстких нарушений — бан навсегда.`, violation: 'hard' };
        }
        return { text: HARD_REFUSAL_REPLY_TEXT, violation: 'hard' };
    }

    return { text: rawReply, violation: null };
}

function escalationCountLabel(userId, kind) {
    const v = getViolationState(userId);
    return kind === 'jb' ? v.jbAttempts : v.illegalAttempts;
}

async function callFreeLLM(prompt, attempt = 1, model = GEMINI_MODEL) {
    const MAX_ATTEMPTS = 4;
    const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`;
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 45000); // 45с — с "размышлением" перед ответом модель отвечает чуть дольше

    let res;
    try {
        res = await fetch(`${url}?key=${GEMINI_API_KEY}`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
                contents: [{ parts: [{ text: prompt }] }],
                generationConfig: {
                    // Модель обдумывает ответ перед тем, как его дать — на КАЖДЫЙ
                    // вопрос (этот вызов — общая точка входа для всего: обычный чат,
                    // анализ файлов, генерация кода, распознанный с фото текст и т.д.).
                    // Само размышление скрыто и не попадает в видимый ответ — только
                    // влияет на его качество.
                    thinkingConfig: { thinkingLevel: 'medium' },
                },
                // Rage/тролль режимы намеренно грубые и токсичные, поэтому
                // немного ослабляем встроенные фильтры Gemini по этим
                // категориям — реальные ограничения (оружие/наркотики,
                // несовершеннолетние, травля по защищённым признакам) всё
                // равно прописаны прямо в наших системных промптах.
                // DANGEROUS_CONTENT добавлен отдельно: с недавних версий
                // Gemini именно под эту категорию нередко попадает грубая
                // ругань/оскорбления, а не только реально опасный контент —
                // без этого ответы в тролль/рейдж-режиме стабильно
                // блокировались на уровне кандидата (finishReason: SAFETY),
                // из-за чего бот выдавал "Пустой ответ от нейросети".
                safetySettings: [
                    { category: 'HARM_CATEGORY_HARASSMENT', threshold: 'BLOCK_ONLY_HIGH' },
                    { category: 'HARM_CATEGORY_HATE_SPEECH', threshold: 'BLOCK_ONLY_HIGH' },
                    { category: 'HARM_CATEGORY_DANGEROUS_CONTENT', threshold: 'BLOCK_ONLY_HIGH' },
                ],
            }),
            signal: controller.signal,
        });
    } catch (e) {
        // Сетевая ошибка на уровне fetch (DNS/обрыв соединения/таймаут) —
        // Node в таких случаях просто пишет "fetch failed" без деталей,
        // поэтому логируем причину отдельно и пробуем ещё раз.
        console.error(`callFreeLLM (Gemini/${model}) network error (попытка ${attempt}):`, e.message, e.cause || '');
        if (attempt < MAX_ATTEMPTS) {
            await new Promise((r) => setTimeout(r, 1500 * attempt));
            return callFreeLLM(prompt, attempt + 1, model);
        }
        throw new Error('Не получилось связаться с нейросетью (Gemini недоступен). Попробуй ещё раз через минуту.');
    } finally {
        clearTimeout(timeout);
    }

    if (res.status === 429) {
        const err = new Error('Сервис перегружен (лимит запросов исчерпан), подожди немного и попробуй снова.');
        err.isQuotaError = true;
        throw err;
    }
    if (res.status === 400 || res.status === 403) {
        const errText = await res.text();
        if (/quota|resource_exhausted/i.test(errText)) {
            const err = new Error('Квота Gemini исчерпана.');
            err.isQuotaError = true;
            throw err;
        }
        throw new Error(`Gemini ${res.status}: проверь GEMINI_API_KEY (${errText.slice(0, 200)})`);
    }
    if (res.status === 404) {
        console.error(`callFreeLLM: модель ${model} недоступна (404)`);
        if (model !== GEMINI_FALLBACK_MODEL) {
            return callFreeLLM(prompt, 1, GEMINI_FALLBACK_MODEL);
        }
        throw new Error(
            `Модель "${model}" больше не существует в Gemini API (Google их часто меняет). ` +
            `Зайди на Render → Environment и задай/поменяй переменную GEMINI_MODEL на актуальное имя модели ` +
            `со страницы https://ai.google.dev/gemini-api/docs/models`
        );
    }
    if (res.status === 503) {
        console.error(`callFreeLLM: модель ${model} перегружена (503), попытка ${attempt}`);
        if (attempt < MAX_ATTEMPTS) {
            await new Promise((r) => setTimeout(r, 1500 * attempt));
            return callFreeLLM(prompt, attempt + 1, model);
        }
        // Последний шанс — пробуем более лёгкую запасную модель, если ещё не на ней
        if (model !== GEMINI_FALLBACK_MODEL) {
            console.error(`callFreeLLM: переключаюсь на запасную модель ${GEMINI_FALLBACK_MODEL}`);
            return callFreeLLM(prompt, 1, GEMINI_FALLBACK_MODEL);
        }
        throw new Error('Серверы Gemini сейчас перегружены (это со стороны Google, не бага бота) — попробуй через минуту-две.');
    }
    if (!res.ok) {
        const errText = await res.text();
        if (/quota|resource_exhausted/i.test(errText)) {
            const err = new Error('Квота Gemini исчерпана.');
            err.isQuotaError = true;
            throw err;
        }
        if (attempt < MAX_ATTEMPTS && res.status >= 500) {
            await new Promise((r) => setTimeout(r, 1500 * attempt));
            return callFreeLLM(prompt, attempt + 1, model);
        }
        throw new Error(`Gemini ${res.status}: ${errText.slice(0, 300)}`);
    }

    const data = await res.json();
    const blockReason = data.promptFeedback && data.promptFeedback.blockReason;
    if (blockReason) {
        throw new Error(`Запрос заблокирован фильтром безопасности Gemini (${blockReason}). Попробуй переформулировать.`);
    }
    const candidate = data.candidates && data.candidates[0];
    if (candidate && candidate.finishReason === 'SAFETY') {
        const flagged = (candidate.safetyRatings || [])
            .filter((r) => r.probability && r.probability !== 'NEGLIGIBLE' && r.probability !== 'LOW')
            .map((r) => r.category.replace('HARM_CATEGORY_', ''))
            .join(', ');
        throw new Error(`Ответ заблокирован встроенным фильтром безопасности Gemini${flagged ? ` (${flagged})` : ''} — попробуй смягчить формулировку.`);
    }
    const parts = candidate && candidate.content && candidate.content.parts;
    const text = parts ? parts.map((p) => p.text || '').join('') : '';
    if (!text.trim()) throw new Error('Пустой ответ от нейросети.');
    return text.trim();
}

// ====== АНАЛИЗ ФАЙЛОВ (в т.ч. обфусцированных) ======
const MAX_FILE_BYTES = 10 * 1024 * 1024; // 10 МБ (обфусцированные файлы могут весить много)
const MAX_ANALYZE_CHARS = 12000; // сколько символов реально уходит в промпт

// Простые эвристики "на глаз", результат добавляется как подсказка модели
function quickHeuristics(text) {
    const flags = [];
    const checks = [
        [/\beval\s*\(/i, 'вызов eval()'],
        [/new\s+Function\s*\(/i, 'создание функции из строки (Function constructor)'],
        [/child_process/i, 'использование child_process (запуск системных команд)'],
        [/require\(\s*['"]net['"]\s*\)/i, 'работа с сырыми сетевыми сокетами (net)'],
        [/atob\s*\(|Buffer\.from\([^,]+,\s*['"]base64['"]\)/i, 'декодирование base64'],
        [/powershell|cmd\.exe|\/bin\/sh|\/bin\/bash/i, 'запуск команд оболочки'],
        [/curl\s|wget\s|http\.get\(|https\.get\(|fetch\(/i, 'сетевые запросы/скачивание'],
        [/process\.env/i, 'обращение к переменным окружения (могут быть секреты)'],
        [/fs\.(unlink|rm|writeFile).*(system32|\/etc\/|\.ssh)/i, 'изменение системных/чувствительных файлов'],
        [/\\x[0-9a-f]{2}(\\x[0-9a-f]{2}){10,}/i, 'длинные hex-последовательности (возможная обфускация)'],
    ];
    for (const [re, label] of checks) {
        if (re.test(text)) flags.push(label);
    }
    const longestLine = Math.max(...text.split('\n').map((l) => l.length));
    if (longestLine > 2000) flags.push('очень длинные строки без переносов (похоже на минификацию/обфускацию)');
    return flags;
}

