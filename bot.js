bot.on('document', async (msg) => {
    const chatId = msg.chat.id;
    registerUser(msg);
    if (isBanned(chatId)) return;
    if (!botEnabled && !isAdmin(chatId)) {
        await bot.sendMessage(chatId, '🛠 Бот временно не работает, вернитесь позже.');
        return;
    }

    const doc = msg.document;
    if (doc.file_size && doc.file_size > MAX_FILE_BYTES) {
        await bot.sendMessage(chatId, `⚠️ Файл больше ${MAX_FILE_BYTES / 1024 / 1024} МБ, не могу проверить.`);
        return;
    }

    const isPdf = /\.pdf$/i.test(doc.file_name || '') || doc.mime_type === 'application/pdf';

    try {
        await bot.sendChatAction(chatId, 'typing');
        const link = await bot.getFileLink(doc.file_id);
        const res = await fetch(link);
        const buf = Buffer.from(await res.arrayBuffer());

        if (isPdf) {
            const pdfText = await extractPdfText(buf);
            if (!pdfText.trim()) {
                await bot.sendMessage(chatId, '📄 Не получилось извлечь текст из PDF — возможно, это скан-картинка без текстового слоя.');
                return;
            }
            const summary = await summarizePdf(doc.file_name || 'file.pdf', pdfText);
            await bot.sendMessage(chatId, `📄 Содержание файла «${doc.file_name || 'файл'}»:\n\n${summary}`);
            return;
        }

        // Грубая проверка, что это текстовый/кодовый файл, а не бинарник
        const sampleText = buf.toString('utf8', 0, Math.min(buf.length, 2000));
        const nonPrintableRatio = (sampleText.match(/[^\x09\x0A\x0D\x20-\x7Eа-яА-ЯёЁ]/g) || []).length / Math.max(sampleText.length, 1);
        if (nonPrintableRatio > 0.3) {
            await bot.sendMessage(chatId, '📄 Похоже, это бинарный файл (не код/текст/PDF) — такой анализ пока не поддерживается. Пришли скрипт, конфиг, package.json или PDF.');
            return;
        }

        const text = buf.toString('utf8');
        const wantsReview = isReviewRequest(msg.caption || '');
        if (wantsReview) {
            const review = await reviewCodeContent(doc.file_name || 'file', text);
            await bot.sendMessage(chatId, `🔍 Ревью кода «${doc.file_name || 'файл'}»:\n\n${review}`);
        } else {
            // Проверка файла на безопасность — не чаще одного раза в сутки на
            // человека, и запускается только по явному нажатию кнопки, а не
            // автоматически при загрузке файла.
            const userId = msg.from?.id || chatId;
            if (usedToday(verifyUsedDate, userId)) {
                await bot.sendMessage(chatId, '🛡 На сегодня проверка файла на безопасность уже использована (доступна 1 раз в день). Возвращайся завтра — лимит обновится автоматически.');
                return;
            }
            pendingVerification.set(userId, {
                chatId,
                fileName: doc.file_name || 'file',
                text,
                expires: Date.now() + PENDING_ACTION_TTL_MS,
            });
            await bot.sendMessage(
                chatId,
                `🛡 Готов проверить файл «${doc.file_name || 'файл'}» на безопасность.\n\nНа сегодня доступна 1 проверка файла — нажми кнопку ниже, чтобы запустить сканирование.`,
                { reply_markup: { inline_keyboard: [[{ text: '🔴 Проверить файл', callback_data: `vf:${userId}` }]] } }
            );
        }
    } catch (e) {
        console.error('file analysis error:', e);
        await bot.sendMessage(chatId, e.isQuotaError ? QUOTA_MESSAGE : `❌ Не получилось проверить файл: ${e.message}`);
    }
});

// ====== OCR ПО ФОТО (скриншот ошибки → правим текущий проект) ======
bot.on('photo', async (msg) => {
    const chatId = msg.chat.id;
    registerUser(msg);
    if (isBanned(chatId)) return;
    if (!botEnabled && !isAdmin(chatId)) {
        await bot.sendMessage(chatId, '🛠 Бот временно не работает, вернитесь позже.');
        return;
    }
    const userId = msg.from?.id || chatId;

    try {
        await bot.sendChatAction(chatId, 'typing');
        const photo = msg.photo[msg.photo.length - 1]; // самое высокое разрешение из присланных размеров
        const link = await bot.getFileLink(photo.file_id);
        const res = await fetch(link);
        const buf = Buffer.from(await res.arrayBuffer());

        const worker = await createWorker('rus+eng');
        let ocrText = '';
        let confidence = null;
        try {
            const { data } = await worker.recognize(buf);
            ocrText = (data.text || '').trim();
            confidence = typeof data.confidence === 'number' ? data.confidence : null;
        } finally {
            await worker.terminate();
        }

        if (!looksLikeRealText(ocrText, confidence)) {
            await bot.sendMessage(chatId, '🖼 На картинке нет текста.');
            return;
        }

        // Проверяем безопасность распознанного текста ДО того, как он куда-либо
        // попадёт (в ответ пользователю или в промпт генерации кода) — иначе
        // картинка становится способом обойти текстовые ограничения бота.
        const isDangerous = await checkOcrTextSafety(ocrText);
        if (isDangerous) {
            const { justBanned, permanent } = recordHardViolation(userId);
            const banNote = justBanned ? '\n\n🚫 Это была 5-я попытка задать вопрос из категории жёстких нарушений — бан навсегда.' : '';
            await bot.sendMessage(chatId, `${HARD_REFUSAL_REPLY_TEXT}${banNote}`);
            return;
        }
        const safeOcrText = maskForbiddenWords(ocrText);

        if (lastCodeFiles.has(chatId)) {
            const requestText = `Вот текст ошибки, распознанный со скриншота:\n${safeOcrText}\n\nНайди причину этой ошибки в текущем коде проекта и пришли исправленный файл целиком.`;

            if (usedToday(genUsedDate, userId)) {
                await bot.sendMessage(chatId, '💻 На сегодня генерация/исправление кода уже использована (доступна 1 раз в день). Возвращайся завтра.');
                return;
            }
            pendingGeneration.set(String(userId), { chatId, requestText, expires: Date.now() + PENDING_ACTION_TTL_MS });
            await bot.sendMessage(
                chatId,
                `🖼 Распознал ошибку со скриншота, готов найти и исправить.\n\nНа сегодня доступна 1 генерация/правка кода — нажми кнопку, чтобы запустить.`,
                { reply_markup: { inline_keyboard: [[{ text: '🔴 Сгенерировать', callback_data: `gc:${userId}` }]] } }
            );
        } else {
            await bot.sendMessage(
                chatId,
                `🖼 Распознанный текст:\n\n${safeOcrText.slice(0, 1500)}\n\nЕсли это ошибка в коде — сначала попроси меня написать сам код (тогда я буду знать проект), и пришли этот же скрин ещё раз — тогда смогу его исправить.`
            );
        }
    } catch (e) {
        console.error('OCR error:', e);
        await bot.sendMessage(chatId, e.isQuotaError ? QUOTA_MESSAGE : `❌ Не получилось распознать изображение: ${e.message}`);
    }
});

